            $sParts = explode(':', $item['selesai']);
            $diffMinutes = ((int)($sParts[0] ?? 0) * 60 + (int)($sParts[1] ?? 0)) - ((int)($mParts[0] ?? 0) * 60 + (int)($mParts[1] ?? 0));
            $hours = floor($diffMinutes / 60);
            $mins = $diffMinutes % 60;
